"""Investigation synthesis.

An investigation is a reproducible document assembled from stored evidence. The
section bodies are built **deterministically** from the feature snapshot, the
signal decomposition and the counter-thesis — not generated by a model.

Why that way round: the brief's rule is that an LLM may synthesise prose but every
factual statement must reference underlying evidence, and that a model must never
invent market sizes, competitors or supplier relationships. The most reliable way
to honour that is to compose the facts deterministically first, so that an LLM
pass (when enabled) is re-wording text whose every claim already carries an
evidence id. If the LLM is unavailable, the investigation still works — it just
reads more plainly. That is the right failure mode.

Sections whose inputs are missing say INSUFFICIENT EVIDENCE rather than being
quietly omitted, because a reader needs to know what we could not establish.
"""

from __future__ import annotations

import datetime as dt
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from ..core.models import (
    ClinicalTrial,
    Company,
    CompanyCapability,
    DrugMasterFile,
    Event,
    FeatureSnapshot,
    Molecule,
    Opportunity,
)
from ..resolution.focus import focus_company_ids

SECTION_ORDER = (
    ("executive_summary", "Executive summary"),
    ("what_changed", "What changed"),
    ("why_the_signal_fired", "Why the signal fired"),
    ("molecule_landscape", "Molecule landscape"),
    ("developers", "Developers"),
    ("regulatory_landscape", "Regulatory landscape"),
    ("api_supply_landscape", "API supply landscape"),
    ("focus_capability_match", "Focus company capability match"),
    ("potential_customers", "Potential customers"),
    ("patent_exclusivity_context", "Patent and exclusivity context"),
    ("risks", "Risks"),
    ("counter_thesis", "Counter-thesis"),
    ("what_we_do_not_know", "What we do not know"),
    ("recommended_human_investigation", "Recommended human investigation"),
    ("sources", "Sources"),
)

INSUFFICIENT = (
    "INSUFFICIENT EVIDENCE — Molecule Radar's current coverage does not support "
    "a statement here."
)


def build_investigation(
    db: Session, opportunity: Opportunity, *, as_of: dt.date | None = None
) -> list[dict[str, Any]]:
    """Assemble the investigation sections for one opportunity."""
    from ..api.queries import counter_thesis_details, signal_details

    molecule = db.get(Molecule, opportunity.molecule_id)
    counterparty = (
        db.get(Company, opportunity.counterparty_company_id)
        if opportunity.counterparty_company_id else None
    )
    snapshot = db.get(FeatureSnapshot, opportunity.feature_snapshot_id)
    features = dict(snapshot.features or {}) if snapshot else {}
    coverage = features.pop("_coverage", {}) if features else {}
    evidence_map = dict(snapshot.feature_evidence or {}) if snapshot else {}

    signals = signal_details(db, opportunity.id)
    concerns = counter_thesis_details(db, opportunity.id)
    effective_as_of = as_of or opportunity.as_of_date
    mol_name = molecule.preferred_name if molecule else "this molecule"

    sections: dict[str, dict[str, Any]] = {}

    def put(key: str, body: str, evidence_ids: list[str] | None = None,
            availability: str = "AVAILABLE") -> None:
        sections[key] = {
            "body": body.strip(),
            "evidence_ids": evidence_ids or [],
            "availability": availability,
        }

    all_evidence = sorted({eid for s in signals for eid in (s.evidence_ids or [])})

    # --- Executive summary ------------------------------------------------
    put("executive_summary", (
        f"{opportunity.headline}.\n\n"
        f"Opportunity Score {opportunity.opportunity_score:.1f} of 100, from "
        f"{len(signals)} contributing signal(s). Evidence Confidence "
        f"{opportunity.evidence_confidence} "
        f"({opportunity.evidence_confidence_score:.2f} of 1.00). Priority band "
        f"{opportunity.priority_band}.\n\n"
        f"These two measures are independent: the score describes how interesting the "
        f"situation looks, and the confidence describes how much of it we can actually "
        f"evidence. Assessed as at {effective_as_of.isoformat()} using engine "
        f"{opportunity.engine_version}."
    ), all_evidence)

    # --- What changed -----------------------------------------------------
    window_start = effective_as_of - dt.timedelta(days=365)
    recent = db.scalars(
        select(Event).where(
            Event.molecule_id == opportunity.molecule_id,
            Event.event_date >= window_start,
            Event.event_date <= effective_as_of,
        ).order_by(Event.event_date.desc()).limit(25)
    ).all()
    if recent:
        lines = [
            f"- {e.event_date.isoformat()} — {e.summary}" for e in recent if e.event_date
        ]
        put("what_changed", (
            f"{len(recent)} dated event(s) recorded for {mol_name} in the 12 months to "
            f"{effective_as_of.isoformat()}:\n\n" + "\n".join(lines)
        ), [str(e.evidence_id) for e in recent if e.evidence_id])
    else:
        put("what_changed",
            f"No dated events recorded for {mol_name} in the 12 months to "
            f"{effective_as_of.isoformat()} within current coverage.",
            availability="NO_QUALIFYING_SIGNALS")

    # --- Why the signal fired --------------------------------------------
    if signals:
        lines = [
            f"- **+{s.points:.1f} of {s.max_points:.0f}** · {s.signal_key} — {s.explanation}"
            for s in signals
        ]
        total = sum(s.points for s in signals)
        put("why_the_signal_fired", (
            "\n".join(lines)
            + f"\n\nThese contributions sum to {total:.1f}, which is the Opportunity "
              f"Score. The score is nothing more than this sum, so it can be checked "
              f"by hand."
        ), all_evidence)
    else:
        put("why_the_signal_fired", INSUFFICIENT, availability="INSUFFICIENT_EVIDENCE")

    # --- Molecule landscape ----------------------------------------------
    parts = [f"{mol_name}"]
    if molecule and molecule.unii:
        parts.append(f"UNII {molecule.unii}")
    if molecule:
        parts.append(f"class {molecule.molecule_class}")
    landscape = "; ".join(parts) + ".\n\n"
    landscape += _bullet("Distinct trial sponsors identified",
                         features.get("distinct_sponsor_count"))
    landscape += _bullet("Registered trials recorded", features.get("trial_count_total"))
    landscape += _bullet("Active trials at the as-of date",
                         features.get("active_trial_count"))
    landscape += _bullet("Countries with observed development activity",
                         features.get("trial_country_count"))
    put("molecule_landscape", landscape, evidence_map.get("trial_starts_12m", []))

    # --- Developers -------------------------------------------------------
    sponsors = db.execute(
        select(Company.canonical_name, ClinicalTrial.phase, ClinicalTrial.start_date)
        .join(ClinicalTrial, ClinicalTrial.sponsor_company_id == Company.id)
        .where(ClinicalTrial.molecule_id == opportunity.molecule_id)
        .order_by(ClinicalTrial.start_date.desc().nullslast()).limit(25)
    ).all()
    if sponsors:
        lines = [
            f"- {name} — {phase or 'phase not stated'}"
            + (f", started {start.isoformat()}" if start else "")
            for name, phase, start in sponsors
        ]
        put("developers",
            "Companies with registered trials involving this molecule in current "
            "coverage:\n\n" + "\n".join(lines))
    else:
        put("developers",
            "No registered trial sponsors identified in current coverage.",
            availability="DATA_UNAVAILABLE" if not coverage.get("clinical_trials")
            else "NO_QUALIFYING_SIGNALS")

    # --- Regulatory landscape --------------------------------------------
    reg = _bullet("Regulatory filing events, trailing 12 months",
                  features.get("filing_count_12m"))
    reg += _bullet("Regulatory filing events, preceding 12 months",
                   features.get("filing_count_prev_12m"))
    reg += _bullet("Approval events, trailing 12 months",
                   features.get("approval_count_12m"))
    reg += _bullet("Distinct ANDA applicants identified",
                   features.get("distinct_anda_applicant_count"))
    put("regulatory_landscape", reg or INSUFFICIENT,
        evidence_map.get("regulatory_event_count_12m", []))

    # --- API supply landscape --------------------------------------------
    holders = db.execute(
        select(Company.canonical_name, DrugMasterFile.dmf_number,
               DrugMasterFile.available_for_reference)
        .join(DrugMasterFile, DrugMasterFile.holder_company_id == Company.id)
        .where(
            DrugMasterFile.molecule_id == opportunity.molecule_id,
            DrugMasterFile.dmf_type == "2",
            DrugMasterFile.status == "A",
        )
    ).all()
    if holders:
        lines = [
            f"- {name} — DMF {number}"
            + (" (available for reference by ANDAs)" if ref_ready else "")
            for name, number, ref_ready in holders
        ]
        put("api_supply_landscape", (
            f"{len(holders)} active Type II drug master file holder(s) identified in "
            f"Molecule Radar's current public-source coverage:\n\n" + "\n".join(lines)
            + "\n\nThis reflects US drug master file filings only. A supplier serving "
              "non-US markets, or manufacturing captively, need not appear here, so "
              "this is not a complete global supplier census."
        ), evidence_map.get("observed_api_supplier_count", []))
    else:
        put("api_supply_landscape",
            "No active Type II drug master file holders identified in current coverage."
            + ("" if coverage.get("dmf") else " Drug master file data has not been ingested."),
            availability="DATA_UNAVAILABLE" if not coverage.get("dmf")
            else "NO_QUALIFYING_SIGNALS")

    # --- Focus capability match ------------------------------------------
    focus_ids = focus_company_ids(db)
    caps = db.scalars(
        select(CompanyCapability).where(
            CompanyCapability.company_id.in_(focus_ids),
            CompanyCapability.molecule_id == opportunity.molecule_id,
        )
    ).all() if focus_ids else []
    if caps:
        lines = []
        for cap in caps:
            lines.append(
                f"- [{cap.assertion_level}] {cap.capability_type}: {cap.value_text}"
                + (f"\n  Basis for inference: {cap.inference_basis}"
                   if cap.inference_basis else "")
            )
        put("focus_capability_match",
            "Direct capability evidence for this molecule:\n\n" + "\n".join(lines)
            + "\n\nFACT entries rest on a first-party regulatory record. INFERENCE "
              "entries state their basis and are not statements of fact.",
            [str(c.evidence_id) for c in caps if c.evidence_id])
    else:
        adjacency = features.get("focus_capability_adjacency_score")
        if adjacency is not None:
            put("focus_capability_match", (
                f"No direct capability evidence for this molecule. Adjacency to "
                f"publicly evidenced capability scores {adjacency:.2f} of 1.00, based on "
                f"{features.get('focus_same_ta_api_capability_count', 0)} API "
                f"capability/ies in the same therapeutic area and "
                f"{_class_phrase(features)} "
                f"molecule-class capability.\n\nThis is an inference from public "
                f"evidence about adjacent molecules, not an assessment of internal "
                f"manufacturing feasibility."
            ), evidence_map.get("focus_capability_adjacency_score", []))
        else:
            put("focus_capability_match",
                "No capability evidence has been ingested for the focus company.",
                availability="DATA_UNAVAILABLE")

    # --- Potential customers ---------------------------------------------
    if counterparty is not None:
        cp_signals = [
            s for s in signals if s.signal_key.startswith("counterparty")
        ]
        lines = [f"- {s.explanation}" for s in cp_signals]
        put("potential_customers", (
            f"{counterparty.canonical_name} exhibits public signals consistent with "
            f"potential demand for this API:\n\n" + "\n".join(lines)
            + "\n\nThis is an assessment of publicly observable signals. It is not a "
              "statement that this company requires this API, sources it externally, "
              "or has any relationship with the focus company."
        ))
    else:
        put("potential_customers",
            "This is a portfolio (BUILD) signal rather than a supply (SELL) signal, so "
            "no counterparty is named. Naming a potential customer requires public "
            "evidence that the focus company supplies the API.",
            availability="NO_QUALIFYING_SIGNALS")

    # --- Patent and exclusivity ------------------------------------------
    pat = _bullet("Months to earliest exclusivity expiry",
                  features.get("months_to_next_exclusivity_expiry"))
    pat += _bullet("Months to earliest listed patent expiry",
                   features.get("months_to_next_patent_expiry"))
    pat += _bullet("Months to latest listed patent expiry",
                   features.get("months_to_last_patent_expiry"))
    pat += _bullet("Listed drug-substance patents",
                   features.get("drug_substance_patent_count"))
    if pat:
        pat += (
            "\nOrange Book listing does not establish that a patent is enforceable or "
            "that its claims cover a given product. Freedom-to-operate requires legal "
            "review that Molecule Radar does not perform."
        )
        put("patent_exclusivity_context", pat,
            evidence_map.get("months_to_next_patent_expiry", []))
    else:
        put("patent_exclusivity_context",
            "No patent or exclusivity records identified for this molecule."
            + ("" if coverage.get("orange_book") else " Orange Book data has not been ingested."),
            availability="DATA_UNAVAILABLE" if not coverage.get("orange_book")
            else "NO_QUALIFYING_SIGNALS")

    # --- Risks and counter-thesis ----------------------------------------
    high = [c for c in concerns if c.severity == "HIGH"]
    if high:
        put("risks", "\n".join(f"- **{c.concern_key}** — {c.explanation}" for c in high),
            sorted({e for c in high for e in (c.evidence_ids or [])}))
    else:
        put("risks",
            "No high-severity concerns identified by the skeptic engine from current "
            "evidence. That is not an assurance that none exist.",
            availability="NO_QUALIFYING_SIGNALS")

    if concerns:
        put("counter_thesis", (
            "Reasons this may not be an opportunity, derived from the same structured "
            "evidence as the supporting signals:\n\n"
            + "\n".join(
                f"- [{c.severity}] **{c.concern_key}** — {c.explanation}" for c in concerns
            )
            + "\n\nThese do not reduce the Opportunity Score. They are presented "
              "alongside it so the disagreement is visible rather than averaged away."
        ), sorted({e for c in concerns for e in (c.evidence_ids or [])}))
    else:
        put("counter_thesis",
            "The skeptic engine found no counter-arguments in current evidence. With "
            "thin coverage this is more likely to reflect what we cannot see than a "
            "genuinely unopposed thesis.",
            availability="NO_QUALIFYING_SIGNALS")

    # --- What we do not know ---------------------------------------------
    unknowns = [
        "Pricing, volumes and margins: no licensed commercial dataset is in use, so no "
        "market size or value is stated anywhere in this product.",
        "Existing supply relationships: contracts are not public, so no current "
        "supplier-customer relationship can be confirmed or excluded.",
        "Internal manufacturing feasibility: assessed only against publicly evidenced "
        "capability, never against internal process or capacity data.",
        "Patent enforceability and freedom to operate: requires legal review.",
    ]
    missing = [k for k, present in coverage.items() if not present]
    if missing:
        unknowns.append(
            "Sources not ingested for this molecule: " + ", ".join(sorted(missing))
            + ". Features depending on them were not evaluated, so this assessment is "
              "partial on those dimensions rather than negative."
        )
    put("what_we_do_not_know", "\n".join(f"- {u}" for u in unknowns))

    # --- Recommended human investigation ---------------------------------
    steps = [
        f"Verify the API supply position for {mol_name} against a licensed supplier "
        f"database and direct enquiry; our count reflects US drug master file filings only.",
        "Review the listed patents for enforceability, claim scope and "
        "freedom-to-operate with qualified counsel.",
    ]
    if counterparty is not None:
        steps.append(
            f"Establish {counterparty.canonical_name}'s actual sourcing position through "
            f"commercial channels. Our observation is only that no API filing of its own "
            f"appears in public coverage."
        )
    else:
        steps.append(
            "Assess internal process feasibility, capacity and cost of goods against the "
            "publicly evidenced capability adjacency cited above."
        )
    steps.append(
        "Confirm the regulatory pathway and reference product status in each target market."
    )
    if opportunity.evidence_confidence in ("LOW", "INSUFFICIENT"):
        steps.insert(0, (
            "Treat this as a lead to verify rather than a finding: Evidence Confidence is "
            f"{opportunity.evidence_confidence}, so the underlying picture is thin."
        ))
    put("recommended_human_investigation", "\n".join(f"{i}. {s}" for i, s in enumerate(steps, 1)))

    # --- Sources ----------------------------------------------------------
    put("sources", (
        f"{len(all_evidence)} evidence record(s) support the signals above. Each is "
        f"retrievable through the evidence endpoint and resolves to a specific source "
        f"document with its publisher, licence, retrieval timestamp and checksum. No "
        f"statement in this investigation is drawn from model recollection."
    ), all_evidence)

    return [
        {
            "key": key,
            "title": title,
            "body": sections.get(key, {}).get("body", INSUFFICIENT),
            "evidence_ids": sections.get(key, {}).get("evidence_ids", []),
            "availability": sections.get(key, {}).get(
                "availability", "INSUFFICIENT_EVIDENCE"
            ),
        }
        for key, title in SECTION_ORDER
    ]


def _class_phrase(features: dict[str, Any]) -> str:
    return "a matching" if features.get("focus_class_capability_match") else "no matching"


def _bullet(label: str, value: Any) -> str:
    """Render a feature as a bullet, saying DATA UNAVAILABLE when it is missing.

    Omitting a missing feature would let a reader assume it was measured and found
    to be zero.
    """
    if value is None:
        return f"- {label}: DATA UNAVAILABLE\n"
    return f"- {label}: {value}\n"
